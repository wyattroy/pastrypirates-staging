console.log("assets/ files:", g.filter(f => f.startsWith("assets/")).length);
console.log("package.json present:", g.includes("package.json"));
console.log("package-lock.json present:", g.includes("package-lock.json"));
console.log("scripts/ leaked in:", g.filter(f => f.startsWith("scripts/")).length);
console.log(".planning/ leaked in:", g.filter(f => f.startsWith(".planning/")).length);
