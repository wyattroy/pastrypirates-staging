import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const REPO = "C:/Users/wyatt/Projects/pastrypirates";
const { isGameCode } = require(REPO + "/.claude/hooks/lib/game-code.cjs");
const all = execFileSync("git", ["ls-files"], { cwd: REPO, encoding: "utf8" }).split("\n").filter(Boolean);
const g = all.filter(isGameCode);
console.log("tracked total:", all.length, "-> counted as GAME:", g.length);
console.log("index.html present:", g.includes("index.html"));
